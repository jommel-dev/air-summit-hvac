-- Daily beginning stock counts by brand, product, and capacity.
-- Stores totals only. Serial numbers are not copied.

CREATE TABLE IF NOT EXISTS public.tblbeginning_stock (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_date DATE NOT NULL,
  brand_id BIGINT NULL,
  brand_name TEXT NULL,
  product_id BIGINT NOT NULL,
  product_name TEXT NULL,
  capacity_id BIGINT NOT NULL,
  capacity_name TEXT NULL,
  indoor_stock INTEGER NOT NULL DEFAULT 0,
  outdoor_stock INTEGER NOT NULL DEFAULT 0,
  window_stock INTEGER NOT NULL DEFAULT 0,
  panel_stock INTEGER NOT NULL DEFAULT 0,
  other_stock INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT tblbeginning_stock_snapshot_capacity_uidx UNIQUE (snapshot_date, capacity_id)
);

CREATE INDEX IF NOT EXISTS idx_tblbeginning_stock_snapshot_date
  ON public.tblbeginning_stock (snapshot_date DESC);

-- One row per business date, written in the same transaction as the counts.
-- A later run the same day sees this row and does not count again.
CREATE TABLE IF NOT EXISTS public.tblbeginning_stock_capture (
  snapshot_date DATE PRIMARY KEY,
  row_count INTEGER NOT NULL,
  source VARCHAR(20) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
